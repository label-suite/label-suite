import { useMemo, useState, type KeyboardEvent, type ReactElement, type ReactNode } from "react";
import { ChevronDown, ChevronRight, FileText, Layers, Search, X } from "lucide-react";
import { SITE_MAP_MODULES, SITE_MAP_PAGES, type SiteMapPage } from "./site-map-data";

/**
 * PRD Site Map overview: one tree that shows the whole system at once.
 * Root "入口" -> seven modules -> twenty pages -> each page's features, drawn
 * left to right in SVG. Modules and pages expand and collapse; the first
 * render (SSR included) shows the page level, every module open and every page
 * closed. A search box finds features by name, opens the modules and pages
 * that hold them and highlights the matches.
 * Page nodes keep their spec number and link to the spec; feature nodes link
 * to that subsection's anchor. Pages that are not standalone pages use a
 * different icon and a dashed outline; the legend sits below the tree.
 * Data: ./site-map-data.ts, generated by scripts/gen-site-map-data.mjs from
 * PRD §Site Map and each spec's `## 規格` subsections. Edit the sources and
 * rerun the script; this file only draws the data.
 */

/* ------------------------------------------------------------ colour tokens */

const INK = "#1E1B4B"; // --color-ink
const MUTED = "#64748B"; // --color-ink-muted
const PRIMARY_STRONG = "#4F46E5"; // --color-primary-strong
const PRIMARY_BORDER = "#C7D2FE"; // --color-primary-border
const PRIMARY_SOFT = "#EEF2FF"; // --color-primary-soft (indigo-50)
const SLATE_50 = "#F8FAFC"; // --color-slate-50
const SLATE_200 = "#E2E8F0"; // --color-slate-200
const WHITE = "#FFFFFF"; // --color-white
const FONT = "'Inter','Noto Sans TC','PingFang TC',-apple-system,sans-serif"; // --font-sans
const MONO = "'JetBrains Mono',ui-monospace,SFMono-Regular,Menlo,monospace"; // --font-mono

/** Module colours from prd-writing/references/visualize.md; outlines and connectors only */
const MODULE_COLORS = [
  "#6366F1", // 01 --color-primary
  "#047857", // 02 --color-cta
  "#1D4ED8", // 03 --color-info
  "#8B5CF6", // 04 --color-file-markdown
  "#818CF8", // 05 --color-secondary
]; // 06 onwards: the cycle restarts at 01
const moduleColor = (id: string): string =>
  MODULE_COLORS[(Number(id) - 1) % MODULE_COLORS.length] ?? MUTED;

const ROOT_LABEL = "入口";

/* ------------------------------------------------------------ links */

// Same rule NoteCraft applies to MDX links: docs/specs/<path>.mdx -> /notes/specs/<path>,
// prefixed with the site base when the site is deployed under a sub-path.
const RAW_BASE = (import.meta as ImportMeta & { env?: { BASE_URL?: string } }).env?.BASE_URL ?? "/";
const BASE = RAW_BASE === "/" ? "" : RAW_BASE.replace(/\/+$/, "");
const specHref = (path: string, anchor?: string): string =>
  `${BASE}/notes/specs/${path}${anchor ? `#${encodeURIComponent(anchor)}` : ""}`;

/* ------------------------------------------------------------ layout */

const PAD = 8;
const ROW = 34; // vertical pitch of page nodes
const PAGE_H = 28;
const FROW = 24; // vertical pitch of feature nodes
const FEAT_H = 20;
const GROUP_GAP = 14; // extra space between modules
const ROOT = { x: PAD, w: 76, h: 36 };
const MOD = { x: 128, w: 140, h: 32 };
const PAGE = { x: 304, w: 276 };
const FEAT = { x: 620, w: 320 };
const W_PAGES = PAGE.x + PAGE.w + PAD;
const W_FEATURES = FEAT.x + FEAT.w + PAD;

interface PlacedFeature {
  title: string;
  anchor: string;
  y: number;
  match: boolean;
}

interface PlacedPage extends SiteMapPage {
  y: number;
  open: boolean;
  /** Held open by a search match; the chevron ignores clicks until the search clears */
  forced: boolean;
  placed: PlacedFeature[];
}

interface PlacedModule {
  id: string;
  label: string;
  color: string;
  y: number;
  open: boolean;
  /** Held open by a search match; the chevron ignores clicks until the search clears */
  forced: boolean;
  pages: PlacedPage[];
}

interface Layout {
  modules: PlacedModule[];
  rootY: number;
  height: number;
  width: number;
}

function layout(
  closedModules: ReadonlySet<string>,
  openPages: ReadonlySet<string>,
  query: string,
): Layout {
  const q = query.trim().toLowerCase();
  const isMatch = (title: string): boolean => q !== "" && title.toLowerCase().includes(q);
  let cursor = PAD;
  let anyFeatures = false;
  const modules = SITE_MAP_MODULES.map((m, i): PlacedModule => {
    if (i > 0) cursor += GROUP_GAP;
    const own = SITE_MAP_PAGES.filter((p) => p.spec.startsWith(`${m.id}-`));
    const hasMatch = own.some((p) => p.features.some((f) => isMatch(f.title)));
    const open = hasMatch || !closedModules.has(m.id);
    if (!open) {
      const y = cursor + PAGE_H / 2;
      cursor += ROW;
      return { ...m, color: moduleColor(m.id), y, open, forced: hasMatch, pages: [] };
    }
    const pages = own.map((p): PlacedPage => {
      const y = cursor + PAGE_H / 2;
      const forced = p.features.some((f) => isMatch(f.title));
      const pageOpen = p.features.length > 0 && (forced || openPages.has(p.spec));
      const placed = pageOpen
        ? p.features.map((f, k) => ({ ...f, y: y + k * FROW, match: isMatch(f.title) }))
        : [];
      if (pageOpen) anyFeatures = true;
      cursor += ROW + Math.max(0, placed.length - 1) * FROW;
      return { ...p, y, open: pageOpen, forced, placed };
    });
    const y = (pages[0].y + pages[pages.length - 1].y) / 2;
    return { ...m, color: moduleColor(m.id), y, open, forced: hasMatch, pages };
  });
  const rootY = (modules[0].y + modules[modules.length - 1].y) / 2;
  return {
    modules,
    rootY,
    height: cursor - (ROW - PAGE_H) + PAD,
    width: anyFeatures ? W_FEATURES : W_PAGES,
  };
}

/** Elbow connector: horizontal out of the parent, vertical along the spine, horizontal into the child */
function elbow(x1: number, y1: number, x2: number, y2: number): string {
  const mid = x1 + (x2 - x1) / 2;
  return `M${x1},${y1} H${mid} V${y2} H${x2}`;
}

/** Feature title with the search match in bold */
function highlighted(title: string, query: string): ReactNode {
  const q = query.trim().toLowerCase();
  const at = q ? title.toLowerCase().indexOf(q) : -1;
  if (at < 0) return title;
  return (
    <>
      {title.slice(0, at)}
      <tspan fontWeight={700} fill={PRIMARY_STRONG}>
        {title.slice(at, at + q.length)}
      </tspan>
      {title.slice(at + q.length)}
    </>
  );
}

/** Enter and Space activate an SVG element that acts as a button */
function onActivate(fn: () => void) {
  return (e: KeyboardEvent<SVGGElement>): void => {
    if (e.key === "Enter" || e.key === " ") {
      e.preventDefault();
      fn();
    }
  };
}

const TOTAL_FEATURES = SITE_MAP_PAGES.reduce((n, p) => n + p.features.length, 0);
const NOT_STANDALONE = SITE_MAP_PAGES.filter((p) => !p.standalone).length;
const PAGES_WITH_FEATURES = SITE_MAP_PAGES.filter((p) => p.features.length > 0).map((p) => p.spec);

/* ------------------------------------------------------------ component */

export default function PrdSiteMapTree(): ReactElement {
  const [closedModules, setClosedModules] = useState<ReadonlySet<string>>(() => new Set());
  const [openPages, setOpenPages] = useState<ReadonlySet<string>>(() => new Set());
  const [query, setQuery] = useState("");

  const view = useMemo(
    () => layout(closedModules, openPages, query),
    [closedModules, openPages, query],
  );

  const matches = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return null;
    const hits = SITE_MAP_PAGES.map((p) => p.features.filter((f) => f.title.toLowerCase().includes(q)).length);
    return { features: hits.reduce((a, b) => a + b, 0), pages: hits.filter((n) => n > 0).length };
  }, [query]);

  const toggle = (set: ReadonlySet<string>, key: string): Set<string> => {
    const next = new Set(set);
    if (next.has(key)) next.delete(key);
    else next.add(key);
    return next;
  };

  const expandAll = (): void => {
    setClosedModules(new Set());
    setOpenPages(new Set(PAGES_WITH_FEATURES));
  };
  const collapseAll = (): void => {
    setClosedModules(new Set(SITE_MAP_MODULES.map((m) => m.id)));
    setOpenPages(new Set());
    setQuery("");
  };

  const { modules, rootY, height: H, width: W } = view;

  return (
    <div className="not-prose space-y-3">
      <div className="flex flex-wrap items-center gap-2 text-sm">
        <label className="relative flex min-w-[220px] flex-1 items-center sm:max-w-xs">
          <Search size={14} className="pointer-events-none absolute left-2.5 text-slate-400" aria-hidden="true" />
          <input
            type="search"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === "Escape") setQuery("");
            }}
            placeholder="搜尋功能名稱"
            aria-label="搜尋功能名稱"
            className="w-full rounded-md border border-slate-300 bg-white py-1.5 pl-8 pr-8 text-sm text-slate-900 placeholder:text-slate-400 focus:border-indigo-500 focus:outline-none focus:ring-2 focus:ring-indigo-200"
          />
          {query && (
            <button
              type="button"
              onClick={() => setQuery("")}
              aria-label="清除搜尋"
              className="absolute right-2 rounded p-0.5 text-slate-400 hover:text-slate-600"
            >
              <X size={14} aria-hidden="true" />
            </button>
          )}
        </label>
        <button
          type="button"
          onClick={expandAll}
          className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-slate-700 hover:bg-slate-50"
        >
          全部展開
        </button>
        <button
          type="button"
          onClick={collapseAll}
          className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-slate-700 hover:bg-slate-50"
        >
          全部收合
        </button>
        <span className="text-xs text-slate-500" aria-live="polite">
          {matches
            ? matches.features > 0
              ? `找到 ${matches.features} 個功能，分布在 ${matches.pages} 頁`
              : "沒有符合的功能"
            : `${SITE_MAP_PAGES.length} 頁、${TOTAL_FEATURES} 個功能`}
        </span>
      </div>

      <div className="overflow-x-auto">
        <svg
          viewBox={`0 0 ${W} ${H}`}
          width={W}
          height={H}
          style={{ display: "block", fontFamily: FONT }}
          role="group"
          aria-labelledby="prd-site-map-tree-title"
        >
          <title id="prd-site-map-tree-title">
            {`全站樹狀圖：從${ROOT_LABEL}分出 ${SITE_MAP_MODULES.length} 個模組，共 ${SITE_MAP_PAGES.length} 頁、${TOTAL_FEATURES} 個功能，其中 ${NOT_STANDALONE} 項不是獨立頁面；模組與頁面可以展開收合，每個頁面連到它的規格，每個功能連到規格裡的那一節。`}
          </title>

          {/* connectors: root -> modules */}
          {modules.map((m) => (
            <path
              key={`root-${m.id}`}
              d={elbow(ROOT.x + ROOT.w, rootY, MOD.x, m.y)}
              fill="none"
              stroke={MUTED}
              strokeWidth={1.25}
              strokeLinejoin="round"
            />
          ))}

          {/* connectors: module -> pages, page -> features */}
          {modules.flatMap((m) =>
            m.pages.flatMap((p) => [
              <path
                key={`mod-${p.spec}`}
                d={elbow(MOD.x + MOD.w, m.y, PAGE.x, p.y)}
                fill="none"
                stroke={m.color}
                strokeWidth={1.25}
                strokeLinejoin="round"
              />,
              ...p.placed.map((f) => (
                <path
                  key={`feat-line-${p.spec}-${f.anchor}`}
                  d={elbow(PAGE.x + PAGE.w, p.y, FEAT.x, f.y)}
                  fill="none"
                  stroke={m.color}
                  strokeOpacity={0.6}
                  strokeWidth={1}
                  strokeLinejoin="round"
                />
              )),
            ]),
          )}

          {/* root */}
          <g>
            <rect
              x={ROOT.x}
              y={rootY - ROOT.h / 2}
              width={ROOT.w}
              height={ROOT.h}
              rx={8}
              fill={SLATE_50}
              stroke={MUTED}
              strokeWidth={1.5}
            />
            <text
              x={ROOT.x + ROOT.w / 2}
              y={rootY}
              textAnchor="middle"
              dominantBaseline="central"
              fontSize={14}
              fontWeight={600}
              fill={INK}
            >
              {ROOT_LABEL}
            </text>
          </g>

          {/* modules: click to expand or collapse */}
          {modules.map((m) => {
            const Chevron = m.open ? ChevronDown : ChevronRight;
            const count = SITE_MAP_PAGES.filter((p) => p.spec.startsWith(`${m.id}-`)).length;
            const flip = (): void => {
              if (!m.forced) setClosedModules((s) => toggle(s, m.id));
            };
            return (
              <g
                key={m.id}
                role="button"
                tabIndex={0}
                aria-expanded={m.open}
                aria-disabled={m.forced || undefined}
                aria-label={`模組 ${m.id} ${m.label}，${count} 頁，${m.open ? "收合" : "展開"}`}
                onClick={flip}
                onKeyDown={onActivate(flip)}
                className="group cursor-pointer outline-none focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-indigo-500"
              >
                <rect
                  x={MOD.x}
                  y={m.y - MOD.h / 2}
                  width={MOD.w}
                  height={MOD.h}
                  rx={8}
                  fill={WHITE}
                  stroke={m.color}
                  strokeWidth={1.5}
                  className="transition-colors duration-150 group-hover:fill-slate-50"
                />
                <Chevron x={MOD.x + 6} y={m.y - 7} size={14} color={MUTED} strokeWidth={2} aria-hidden="true" />
                <circle cx={MOD.x + 27} cy={m.y} r={4} fill={m.color} />
                <text x={MOD.x + 37} y={m.y} dominantBaseline="central" fontSize={13} fill={INK}>
                  <tspan fontFamily={MONO} fontSize={12} fill={MUTED}>
                    {m.id}
                  </tspan>
                  <tspan dx={6} fontWeight={600}>
                    {m.label}
                  </tspan>
                </text>
                <text
                  x={MOD.x + MOD.w - 10}
                  y={m.y}
                  textAnchor="end"
                  dominantBaseline="central"
                  fontFamily={MONO}
                  fontSize={11}
                  fill={MUTED}
                >
                  {count}
                </text>
              </g>
            );
          })}

          {/* pages: the chevron expands features, the label opens the spec */}
          {modules.flatMap((m) =>
            m.pages.map((p) => {
              const top = p.y - PAGE_H / 2;
              const Icon = p.standalone ? FileText : Layers;
              const Chevron = p.open ? ChevronDown : ChevronRight;
              const n = p.features.length;
              const flip = (): void => {
                if (!p.forced) setOpenPages((s) => toggle(s, p.spec));
              };
              return (
                <g key={p.spec}>
                  <rect
                    x={PAGE.x}
                    y={top}
                    width={PAGE.w}
                    height={PAGE_H}
                    rx={6}
                    fill={p.standalone ? WHITE : SLATE_50}
                    stroke={p.standalone ? PRIMARY_BORDER : MUTED}
                    strokeWidth={1}
                    strokeDasharray={p.standalone ? undefined : "4 3"}
                  />
                  {n > 0 && (
                    <g
                      role="button"
                      tabIndex={0}
                      aria-expanded={p.open}
                      aria-disabled={p.forced || undefined}
                      aria-label={`${p.open ? "收合" : "展開"} ${p.spec} ${p.label}的 ${n} 個功能`}
                      onClick={flip}
                      onKeyDown={onActivate(flip)}
                      className="group cursor-pointer outline-none focus-visible:outline focus-visible:outline-2 focus-visible:outline-indigo-500"
                    >
                      <rect
                        x={PAGE.x + 1}
                        y={top + 1}
                        width={24}
                        height={PAGE_H - 2}
                        rx={5}
                        fill="transparent"
                        className="transition-colors duration-150 group-hover:fill-indigo-50"
                      />
                      <Chevron x={PAGE.x + 6} y={p.y - 7} size={14} color={MUTED} strokeWidth={2} aria-hidden="true" />
                    </g>
                  )}
                  <a
                    href={specHref(p.path)}
                    aria-label={`規格 ${p.spec} ${p.label}${p.standalone ? "" : "（不是獨立頁面）"}`}
                    className="group outline-none focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-indigo-500"
                  >
                    <title>{`開啟規格 ${p.spec} ${p.label}`}</title>
                    <rect
                      x={PAGE.x + 26}
                      y={top + 1}
                      width={PAGE.w - 27}
                      height={PAGE_H - 2}
                      rx={5}
                      fill="transparent"
                      className="transition-colors duration-150 group-hover:fill-indigo-50"
                    />
                    <Icon
                      x={PAGE.x + 28}
                      y={p.y - 7}
                      size={14}
                      color={p.standalone ? PRIMARY_STRONG : MUTED}
                      strokeWidth={1.75}
                      aria-hidden="true"
                    />
                    <text x={PAGE.x + 50} y={p.y} dominantBaseline="central" fontSize={13} fill={INK}>
                      <tspan fontFamily={MONO} fontSize={12} fill={PRIMARY_STRONG}>
                        {p.spec}
                      </tspan>
                      <tspan dx={8} className="group-hover:underline">
                        {p.label}
                      </tspan>
                    </text>
                  </a>
                  {n > 0 && (
                    <text
                      x={PAGE.x + PAGE.w - 10}
                      y={p.y}
                      textAnchor="end"
                      dominantBaseline="central"
                      fontFamily={MONO}
                      fontSize={11}
                      fill={MUTED}
                      pointerEvents="none"
                    >
                      {n}
                    </text>
                  )}
                </g>
              );
            }),
          )}

          {/* features: each links to its subsection in the spec */}
          {modules.flatMap((m) =>
            m.pages.flatMap((p) =>
              p.placed.map((f) => (
                <a
                  key={`feat-${p.spec}-${f.anchor}`}
                  href={specHref(p.path, f.anchor)}
                  aria-label={`規格 ${p.spec} §${f.title}`}
                  className="group outline-none focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-1 focus-visible:outline-indigo-500"
                >
                  <title>{`開啟規格 ${p.spec} §${f.title}`}</title>
                  <rect
                    x={FEAT.x}
                    y={f.y - FEAT_H / 2}
                    width={FEAT.w}
                    height={FEAT_H}
                    rx={4}
                    fill={f.match ? PRIMARY_SOFT : WHITE}
                    stroke={f.match ? PRIMARY_STRONG : SLATE_200}
                    strokeWidth={f.match ? 1.5 : 1}
                    className="transition-colors duration-150 group-hover:fill-indigo-50"
                  />
                  <text
                    x={FEAT.x + 10}
                    y={f.y}
                    dominantBaseline="central"
                    fontSize={12}
                    fill={INK}
                    className="group-hover:underline"
                  >
                    {highlighted(f.title, query)}
                  </text>
                </a>
              )),
            ),
          )}
        </svg>
      </div>

      <div className="flex flex-wrap items-center gap-x-5 gap-y-2 text-xs text-slate-500">
        <span className="inline-flex items-center gap-1.5">
          <span className="inline-flex h-5 w-5 items-center justify-center rounded border border-indigo-200 bg-white">
            <FileText size={12} className="text-indigo-600" aria-hidden="true" />
          </span>
          獨立頁面
        </span>
        <span className="inline-flex items-center gap-1.5">
          <span className="inline-flex h-5 w-5 items-center justify-center rounded border border-dashed border-slate-500 bg-slate-50">
            <Layers size={12} className="text-slate-500" aria-hidden="true" />
          </span>
          不是獨立頁面（跨頁共用的行為或清單）
        </span>
        <span className="inline-flex items-center gap-1.5">
          <ChevronRight size={12} className="text-slate-500" aria-hidden="true" />
          展開模組的頁面或頁面的功能；右側數字是頁數或功能數
        </span>
        <span>
          <span className="font-mono text-indigo-600">NN-NN</span>{" "}
          是規格編號，點頁面開啟該頁規格，點功能跳到規格裡的那一節
        </span>
      </div>
    </div>
  );
}
